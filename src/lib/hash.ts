/**
 * Deterministic ids. Some records must be the same record on every device
 * without the devices talking first: one weigh-in per date, one favourite per
 * food. Deriving the id from the natural key makes two devices that create
 * "the same thing" offline converge on one row when they sync.
 */

/** cyrb128: a fast, well-distributed 128-bit string hash (not cryptographic). */
function hash128(str: string): [number, number, number, number] {
  let h1 = 1779033703;
  let h2 = 3144134277;
  let h3 = 1013904242;
  let h4 = 2773480762;
  for (let i = 0; i < str.length; i++) {
    const k = str.charCodeAt(i);
    h1 = h2 ^ Math.imul(h1 ^ k, 597399067);
    h2 = h3 ^ Math.imul(h2 ^ k, 2869860233);
    h3 = h4 ^ Math.imul(h3 ^ k, 951274213);
    h4 = h1 ^ Math.imul(h4 ^ k, 2716044179);
  }
  h1 = Math.imul(h3 ^ (h1 >>> 18), 597399067);
  h2 = Math.imul(h4 ^ (h2 >>> 22), 2869860233);
  h3 = Math.imul(h1 ^ (h3 >>> 17), 951274213);
  h4 = Math.imul(h2 ^ (h4 >>> 19), 2716044179);
  h1 ^= h2 ^ h3 ^ h4;
  h2 ^= h1;
  h3 ^= h1;
  h4 ^= h1;
  return [h1 >>> 0, h2 >>> 0, h3 >>> 0, h4 >>> 0];
}

/** A UUID-shaped id that is always the same for the same namespace and key. */
export function stableId(namespace: string, key: string): string {
  const hex = hash128(`${namespace}\u0000${key}`)
    .map((n) => n.toString(16).padStart(8, '0'))
    .join('');
  // Mark it as a name-based UUID (version 5 layout, RFC 4122 variant) so any UUID column accepts it.
  const variant = ((parseInt(hex[16], 16) & 0x3) | 0x8).toString(16);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-${variant}${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}
